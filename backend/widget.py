#: Bumped when the compiled shape changes in a way a cached file cannot satisfy.
COMPILER = 1

#: A spec is a description, not a document. Anything past this is a narrator
#: trying to write a page.
MAX_SPEC_BYTES = 24_000
MAX_ELEMENTS = 60
MAX_TEXT = 400
MAX_ROWS = 40
MAX_COLUMNS = 6
#: A grid cell's `mark` glyph, in codepoints. Wide enough for a real emoji with a
#: variation selector or a keycap sequence, narrow enough that a sentence is not one:
#: a mark is a symbol, and a longer string is a `note` wearing the wrong field.
MAX_MARK = 4
#: A relationship graph's ceilings. Nodes are laid out by the backend on a ring,
#: so past a couple dozen the labels overlap and it stops being readable — the cap
#: is a legibility bound, not only a safety one.
MAX_NODES = 24
MAX_EDGES = 60
#: How deep a tree may nest before it is refused as either a cycle or unreadable.
MAX_TREE_DEPTH = 12

#: The closed set. A kind absent here is refused, never skipped.
ELEMENT_KINDS: frozenset[str] = frozenset(
    {
        "heading",
        "text",
        "note",
        "stat",
        "bar",
        "keyvalue",
        "list",
        "table",
        "choice",
        "divider",
        # Spatial / relational kinds. The narrator declares STRUCTURE (cells,
        # nodes, edges, parents) and never geometry — every coordinate below is
        # computed here, so a scene map cannot smuggle markup or a layout exploit.
        "grid",
        "links",
        "tree",
    }
)

_ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
_PATH_RE = re.compile(r"^[a-zA-Z_][a-zA-Z0-9_]*(\.[a-zA-Z_][a-zA-Z0-9_]*)*$")


class SceneSpecError(ValueError):
    """A spec that cannot become a scene. Names the field so the narrator can fix
    the one thing that was wrong."""

    def __init__(self, field: str, expected: str) -> None:
        super().__init__(f"{field}: {expected}")
        self.field = field
        self.expected = expected


