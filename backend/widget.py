# ── binding ──────────────────────────────────────────────────────────────


def resolve_bind(path: str, state: dict[str, Any]) -> Any:
    """Read a dotted path out of run state, or raise.

    Still raises on an unresolvable path — but the caller (``_valued``) now catches
    that and falls back to the element's literal ``value``/``text``, dropping the
    element only when there is no literal either. A malformed PATH (not a typo'd
    one, but a shape that could walk into internals) is refused here regardless.
    """
    if not isinstance(path, str) or not _PATH_RE.match(path):
        raise SceneSpecError("bind", f"a dotted path, got {path!r}")
    node: Any = state
    for part in path.split("."):
        if not isinstance(node, dict) or part not in node:
            raise SceneSpecError("bind", f"nothing at {path!r}")
        node = node[part]
    return node


# ── compiling ────────────────────────────────────────────────────────────


def _text(value: Any, field: str, *, cap: int = MAX_TEXT) -> str:
    """Coerce a scalar to display text, truncating rather than refusing.

    A legible partial beats a blank frame: an over-long string is cut to the cap
    with an ellipsis, and an unexpected scalar (bool, etc.) is stringified. Only a
    genuinely unrenderable container (dict/list) is refused, so the ONE element
    carrying it is dropped by the salvage loop instead of the whole scene.
    """
    if value is None:
        return ""
    if isinstance(value, (dict, list)):
        raise SceneSpecError(field, "text")
    out = str(value)
    if len(out) > cap:
        out = out[: max(1, cap - 1)] + "…"
    return out


def _celltext(value: Any, field: str, *, cap: int = MAX_TEXT) -> str:
    """``_text`` that degrades a bad cell to empty rather than dropping its whole
    container — used where one broken cell should not cost the entire table/graph."""
    try:
        return _text(value, field, cap=cap)
    except SceneSpecError:
        return ""


def _valued(el: dict[str, Any], where: str, bound: Any, bind_failed: bool, key: str) -> Any:
    """The value a value-bearing element should show: the resolved bind if it
    resolved, else the element's literal. A bind that failed AND has no literal to
    fall back to raises, so the salvage loop drops just that element (item 5)."""
    if "bind" in el and not bind_failed:
        return bound
    literal = el.get(key)
    if bind_failed and literal is None:
        raise SceneSpecError(f"{where}.bind", "unresolved, and no literal fallback")
    return literal


def _esc(value: Any) -> str:
    """Every narrator string passes through here on its way to the DOM.

    Escaping AND framing removal, in that order, because a scene is a second
    route to the DOM and R18 applies to both. Reusing the prose stripper rather
    than writing a second one: two implementations of "what counts as framing"
    would drift, and the one in ``view`` is the one with the tests that prove it
    keeps the words inside a box.
    """
    return html.escape(strip_terminal_framing(str(value)), quote=True)


def _pct(value: Any, cap: Any) -> float | None:
    try:
        v, c = float(value), float(cap)
    except (TypeError, ValueError):
        return None
    if c <= 0:
        return None
    return max(0.0, min(1.0, v / c))


def _element(el: Any, index: int, state: dict[str, Any]) -> str:
    where = f"elements[{index}]"
    if not isinstance(el, dict):
        raise SceneSpecError(where, "an object")
    kind = el.get("kind")
    if kind not in ELEMENT_KINDS:
        raise SceneSpecError(f"{where}.kind", f"one of {sorted(ELEMENT_KINDS)}, got {kind!r}")

    # A bound value replaces `value`/`text`. An unresolvable bind is NOT fatal
    # here: it falls back to the element's literal, and drops only this element
    # (via the salvage loop) when there is no literal to fall back to.
    bound: Any = None
    bind_failed = False
    if "bind" in el:
        try:
            bound = resolve_bind(el["bind"], state)
        except SceneSpecError:
            bind_failed = True

    if kind == "divider":
        return "<hr>"

    if kind == "heading":
        return f"<h3>{_esc(_text(el.get('text'), f'{where}.text'))}</h3>"

    if kind in ("text", "note"):
        raw = _valued(el, where, bound, bind_failed, "text")
        body = _esc(_text(raw, f"{where}.text"))
        return f'<p class="n">{body}</p>' if kind == "note" else f"<p>{body}</p>"

    if kind == "keyvalue":
        label = _esc(_text(el.get("label"), f"{where}.label"))
        raw = _valued(el, where, bound, bind_failed, "value")
        value = _esc(_text(raw, f"{where}.value"))
        return f'<div class="r"><div class="k">{label}</div><div class="v">{value}</div></div>'

    if kind in ("stat", "bar"):
        label = _esc(_text(el.get("label"), f"{where}.label"))
        raw = _valued(el, where, bound, bind_failed, "value")
        value = _esc(_text(raw, f"{where}.value", cap=64))
        cap = el.get("max")
        pct = _pct(raw, cap) if cap is not None else None
        tail = (
            f'<span class="n"> / {_esc(_text(cap, f"{where}.max", cap=32))}</span>'
            if cap is not None
            else ""
        )
        bar = (
            f'<div class="t"><div class="f" style="width:{round(pct * 100)}%"></div></div>'
            if pct is not None
            else ""
        )
        return (
            f'<div class="r"><div class="k">{label}</div>'
            f'<div class="v">{value}{tail}{bar}</div></div>'
        )

    if kind == "list":
        items = el.get("items")
        if not isinstance(items, list):
            raise SceneSpecError(f"{where}.items", "an array")
        items = items[:MAX_ROWS]  # truncate rather than reject
        cells: Any = "".join(
            f"<li>{_esc(_celltext(i, f'{where}.items[{n}]'))}</li>" for n, i in enumerate(items)
        )
        return f"<ul>{cells}</ul>"

    if kind == "table":
        cols = el.get("columns")
        if not isinstance(cols, list) or not cols:
            raise SceneSpecError(f"{where}.columns", "a non-empty array")
        cols = cols[:MAX_COLUMNS]  # truncate wide headers
        rows = el.get("rows")
        rows = rows[:MAX_ROWS] if isinstance(rows, list) else []
        head = "".join(
            f"<th>{_esc(_celltext(c, f'{where}.columns[{n}]'))}</th>" for n, c in enumerate(cols)
        )
        body = ""
        for rn, row in enumerate(rows):
            if not isinstance(row, list):
                continue  # drop a non-array row, keep the table
            cells = list(row[: len(cols)])  # truncate a long row
            cells += [""] * (len(cols) - len(cells))  # pad a short row
            body += (
                "<tr>"
                + "".join(
                    f"<td>{_esc(_celltext(c, f'{where}.rows[{rn}][{cn}]'))}</td>"
                    for cn, c in enumerate(cells)
                )
                + "</tr>"
            )
        return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"

    if kind == "grid":
        cols = el.get("columns")
        if not isinstance(cols, int) or isinstance(cols, bool):
            cols = 1
        cols = max(1, min(8, cols))  # clamp into range rather than reject
        cells = el.get("cells")
        if not isinstance(cells, list) or not cells:
            raise SceneSpecError(f"{where}.cells", "a non-empty array")
        cells = cells[:MAX_ROWS]  # truncate rather than reject
        out = []
        for cn, c in enumerate(cells):
            if not isinstance(c, dict):
                continue  # drop a bad cell, keep the grid
            label = _esc(_celltext(c.get("label"), f"{where}.cells[{cn}].label", cap=64))
            note = c.get("note")
            nt = _esc(_celltext(note, f"{where}.cells[{cn}].note", cap=64))
            note_html = f'<span class="gn">{nt}</span>' if note not in (None, "") else ""
            # `mark` carries two different intentions and both are honoured, because
            # collapsing them loses information either way. A GLYPH (a string) is a
            # per-cell symbol and renders as a badge: it distinguishes cells from each
            # other, which is what a map needs. `true` is a whole-cell highlight and
            # tints the box. A glyph deliberately does NOT also tint: a narrator marks
            # every cell of a map with its own symbol, and tinting on any mark made all
            # six cells identically purple — a highlight that highlights everything
            # says nothing, and the symbols themselves were dropped on the floor.
            #
            # The glyph is escaped narrator TEXT, like a label or a note. `columns`
            # (a validated int) and the tint class remain the only non-narrator values
            # reaching markup, so no coordinate or class is ever author text.
            mark = c.get("mark")
            badge = ""
            tint = ""
            if isinstance(mark, str):
                glyph = mark.strip()
                # A mark is a symbol, not a sentence. Past the cap it is dropped
                # WHOLE rather than cut: an emoji is a codepoint sequence, and
                # truncating one renders a lone variation selector or joiner.
                if glyph and len(glyph) <= MAX_MARK:
                    badge = f'<span class="gmk">{_esc(glyph)}</span>'
            elif mark:
                tint = " gm"
            out.append(f'<div class="gc{tint}">{badge}{label}{note_html}</div>')
        return (
            f'<div class="grid" style="grid-template-columns:repeat({cols},1fr)">'
            + "".join(out)
            + "</div>"
        )

    if kind == "links":
        nodes = el.get("nodes")
        if not isinstance(nodes, list) or not nodes:
            raise SceneSpecError(f"{where}.nodes", "a non-empty array")
        nodes = nodes[:MAX_NODES]  # truncate rather than reject
        seen: dict[str, str] = {}
        parsed_nodes: list[tuple[str, str]] = []
        for nn, n in enumerate(nodes):
            if not isinstance(n, dict):
                continue  # drop a malformed node
            nid = n.get("id")
            if not isinstance(nid, str) or not _ID_RE.match(nid):
                continue  # drop a node with no usable id
            if nid in seen:
                continue  # de-dup, keeping the first
            label = _celltext(n.get("label"), f"{where}.nodes[{nn}].label", cap=48)
            seen[nid] = label
            parsed_nodes.append((nid, label))
        if not parsed_nodes:
            raise SceneSpecError(f"{where}.nodes", "no renderable node")
        edges = el.get("edges")
        edges = edges[:MAX_EDGES] if isinstance(edges, list) else []
        parsed_edges: list[tuple[str, str, str]] = []
        for en, e in enumerate(edges):
            if not isinstance(e, dict):
                continue  # drop a malformed edge
            a, b = e.get("from"), e.get("to")
            if a not in seen or b not in seen:
                continue  # drop an edge to an undeclared node
            lbl = e.get("label")
            lf = f"{where}.edges[{en}].label"
            elabel = _celltext(lbl, lf, cap=32) if lbl not in (None, "") else ""
            parsed_edges.append((a, b, elabel))
        return _render_links(parsed_nodes, parsed_edges)

    if kind == "tree":
        nodes = el.get("nodes")
        if not isinstance(nodes, list) or not nodes:
            raise SceneSpecError(f"{where}.nodes", "a non-empty array")
        nodes = nodes[:MAX_ROWS]  # truncate rather than reject
        byid: dict[str, dict[str, Any]] = {}
        order: list[str] = []
        for nn, n in enumerate(nodes):
            if not isinstance(n, dict):
                continue  # drop a malformed node
            nid = n.get("id")
            if not isinstance(nid, str) or not _ID_RE.match(nid):
                continue  # drop a node with no usable id
            if nid in byid:
                continue  # de-dup, keeping the first
            label = _celltext(n.get("label"), f"{where}.nodes[{nn}].label", cap=64)
            note = n.get("note")
            nf = f"{where}.nodes[{nn}].note"
            note_s = _celltext(note, nf, cap=64) if note not in (None, "") else ""
            parent = n.get("parent")
            if not isinstance(parent, str) or not parent:
                parent = None
            byid[nid] = {"label": label, "note": note_s, "parent": parent, "children": []}
            order.append(nid)
        if not byid:
            raise SceneSpecError(f"{where}.nodes", "no renderable node")
        # An undeclared parent is treated as a root rather than a fatal error.
        roots: list[str] = []
        for nid in order:
            parent = byid[nid]["parent"]
            if parent is None or parent not in byid:
                byid[nid]["parent"] = None
                roots.append(nid)
            else:
                byid[parent]["children"].append(nid)
        # No root at all (every node points at another — a cycle): promote the first.
        if not roots:
            first = order[0]
            byid[first]["parent"] = None
            for k in byid:
                if first in byid[k]["children"]:
                    byid[k]["children"].remove(first)
            roots.append(first)
        visited: set[str] = set()

        def _branch(nid: str, depth: int) -> str:
            # A back-edge or an over-deep branch is dropped, not fatal.
            if nid in visited or depth > MAX_TREE_DEPTH:
                return ""
            visited.add(nid)
            node = byid[nid]
            note_html = f' <span class="tn">{_esc(node["note"])}</span>' if node["note"] else ""
            inner = f"{_esc(node['label'])}{note_html}"
            kids = "".join(_branch(k, depth + 1) for k in node["children"])
            if kids:
                inner += "<ul>" + kids + "</ul>"
            return f"<li>{inner}</li>"

        branches = "".join(_branch(r, 0) for r in roots)
        # Any node still unreached (stranded by a cycle) is promoted as its own root.
        for nid in order:
            if nid not in visited:
                branches += _branch(nid, 0)
        return '<ul class="tree">' + branches + "</ul>"

    # choice
    cid = el.get("id")
    if not isinstance(cid, str) or not _ID_RE.match(cid):
        raise SceneSpecError(f"{where}.id", "a slug (a-z, 0-9, hyphen)")
    label = _esc(_text(el.get("label"), f"{where}.label"))
    # The id rides in a data attribute, never in generated script.
    return f'<button type="button" data-choice="{_esc(cid)}">{label}</button>'


def _render_links(nodes: list[tuple[str, str]], edges: list[tuple[str, str, str]]) -> str:
    """A relationship graph as inline SVG, laid out by the backend on a ring.

    The narrator supplies nodes and edges and NEVER a coordinate — every x/y here
    is computed from the node's ring position, so this stays inside the same trust
    boundary as the rest of the compiler: structure from the narrator, geometry
    from the app. Labels are the only narrator strings and each is escaped."""
    import math

    n = len(nodes)
    w, h = 320.0, 220.0
    cx, cy = w / 2, h / 2
    radius = min(w, h) / 2 - 34
    pos: dict[str, tuple[float, float]] = {}
    for i, (nid, _label) in enumerate(nodes):
        # A lone node sits at the centre; otherwise evenly spaced from the top.
        if n == 1:
            pos[nid] = (cx, cy)
        else:
            ang = -math.pi / 2 + 2 * math.pi * i / n
            pos[nid] = (cx + radius * math.cos(ang), cy + radius * math.sin(ang))
    parts = [f'<svg class="lk" viewBox="0 0 {w:.0f} {h:.0f}" role="img">']
    for a, b, lbl in edges:  # edges first, so nodes draw on top
        x1, y1 = pos[a]
        x2, y2 = pos[b]
        parts.append(f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" class="lke"/>')
        if lbl:
            parts.append(
                f'<text x="{(x1 + x2) / 2:.1f}" y="{(y1 + y2) / 2:.1f}" class="lkl">{_esc(lbl)}</text>'
            )
    for nid, label in nodes:
        x, y = pos[nid]
        parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="5" class="lkn"/>')
        parts.append(f'<text x="{x:.1f}" y="{y - 9:.1f}" class="lknt">{_esc(label)}</text>')
    parts.append("</svg>")
    return '<div class="lkwrap">' + "".join(parts) + "</div>"


def _compile_scene(
    scene_id: str, spec: dict[str, Any], state: dict[str, Any], *, nonce: str = ""
) -> tuple[str, list[dict[str, Any]]]:
    """The salvaging core: ``(html, dropped)``.

    The WHOLE-spec gates (id, byte ceiling, markup ban, non-empty elements) are the
    trust boundary and stay hard — they raise. Per-ELEMENT faults are soft: a bad
    element is dropped, recorded in ``dropped``, and the rest render, because a
    legible partial scene beats a blank frame. Every string is still HTML-escaped.
    """
    if not isinstance(scene_id, str) or not _ID_RE.match(scene_id):
        raise SceneSpecError("sceneId", "a slug (a-z, 0-9, hyphen)")
    if not isinstance(spec, dict):
        raise SceneSpecError("spec", "an object")

    size = len(json.dumps(spec, ensure_ascii=False).encode("utf-8"))
    if size > MAX_SPEC_BYTES:
        raise SceneSpecError("spec", f"at most {MAX_SPEC_BYTES} bytes, got {size}")

    for banned in ("html", "innerHTML", "script", "srcdoc", "style"):
        if banned in spec:
            raise SceneSpecError(f"spec.{banned}", "a scene is described, not written")

    elements = spec.get("elements")
    if not isinstance(elements, list) or not elements:
        raise SceneSpecError("spec.elements", "a non-empty array")
    elements = elements[:MAX_ELEMENTS]  # truncate rather than reject the whole scene

    title = _text(spec.get("title"), "spec.title", cap=120)

    dropped: list[dict[str, Any]] = []
    parts: list[str] = []
    for i, el in enumerate(elements):
        try:
            parts.append(_element(el, i, state))
        except SceneSpecError as exc:
            # One bad element is skipped, not fatal — its loss is recorded so the
            # narrator can be told, but the scene still mounts and renders.
            dropped.append({"index": i, "field": exc.field, "reason": exc.expected})
    body = "".join(parts)

    # The CSP meta is the FIRST thing in <head>, ahead of every generated byte: a
    # policy that arrives after the content it governs has already lost.
    html_out = (
        '<!DOCTYPE html><html lang="zh" data-scene="'
        + _esc(scene_id)
        + '"'
        + ' data-nonce="'
        + _esc(nonce)
        + '"><head>'
        '<meta charset="utf-8">'
        f'<meta http-equiv="Content-Security-Policy" content="{CSP}">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"{_STYLE}</head><body>"
        + (f"<h3>{_esc(title)}</h3>" if title else "")
        + body
        + SCENE_SCRIPT
        + "</body></html>"
    )
    return html_out, dropped


def compile_scene(
    scene_id: str, spec: dict[str, Any], state: dict[str, Any], *, nonce: str = ""
) -> str:
    """A spec plus run state becomes one self-contained document.

    Fail-soft per element: one bad element is dropped and the rest render, so a
    single typo never turns the whole scene into a blank box. The whole-spec gates
    (markup ban, byte ceiling, empty elements) stay hard. Use ``scene_warnings`` to
    learn what was dropped so the narrator can fix it on its next turn.
    """
    html_out, _dropped = _compile_scene(scene_id, spec, state, nonce=nonce)
    return html_out


def scene_warnings(
    scene_id: str, spec: dict[str, Any], state: dict[str, Any], *, nonce: str = ""
) -> list[dict[str, Any]]:
    """The dropped-element records for a spec — never raises.

    The mount/update tools return this so the narrator learns what would not
    render. A whole-spec hard gate (markup / size / empty) surfaces as one warning
    (index ``-1``) rather than an exception, so the mount itself still succeeds.
    """
    try:
        _html, dropped = _compile_scene(scene_id, spec, state, nonce=nonce)
        return dropped
    except SceneSpecError as exc:
        return [{"index": -1, "field": exc.field, "reason": exc.expected}]


# ── caching, per run ────────────────────────────────────────────────────


def spec_digest(spec: dict[str, Any], state_slice: Any = None) -> str:
    """Identity of a compiled scene: the spec plus the compiler that made it.

    ``state_slice`` participates because a bound scene showing last month's
    numbers is exactly the drift this module exists to prevent — a cache hit must
    mean "the same picture", not "the same description".
    """
    payload = json.dumps(
        {"c": COMPILER, "spec": spec, "s": state_slice},
        ensure_ascii=False,
        sort_keys=True,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def bound_values(spec: dict[str, Any], state: dict[str, Any]) -> dict[str, Any]:
    """Every value this spec binds, read from state.

    Derived from the spec rather than passed in, so the cache key and the render
    can never disagree about which paths matter. An unresolvable path contributes
    a sentinel instead of raising: this runs to build a KEY, and the real refusal
    belongs to the compile pass where the field can be named.
    """
    out: dict[str, Any] = {}
    for el in spec.get("elements") or []:
        if not isinstance(el, dict):
            continue
        path = el.get("bind")
        if not isinstance(path, str):
            continue
        try:
            out[path] = resolve_bind(path, state)
        except SceneSpecError:
            out[path] = "\u0000unresolved"
    return out


def widget_path(data_dir: Path, run_id: str, scene_id: str) -> Path:
    """Compiled HTML lives under the RUN, never the world.

    Specs travel between players; compiled bytes do not. Keeping them here is
    what makes "widget bytes are always locally produced" true even for a world
    pack that came from someone else.
    """
    if not _ID_RE.match(run_id) or not _ID_RE.match(scene_id):
        raise SceneSpecError("path", "a slug run id and scene id")
    return data_dir / "runs" / run_id / "widgets" / f"{scene_id}.html"


def compile_cached(
    data_dir: Path,
    run_id: str,
    scene_id: str,
    spec: dict[str, Any],
    state: dict[str, Any],
    *,
    bound_slice: Any = None,
    nonce: str = "",
) -> tuple[str, bool]:
    """``(html, from_cache)``. Recompiles whenever the digest moves."""
    # The nonce participates: a remount issues a new one, and a cached file
    # carrying the old one would let a replaced scene answer for its successor.
    digest = spec_digest(spec, {"b": bound_slice, "n": nonce})
    target = widget_path(data_dir, run_id, scene_id)
    marker = target.with_suffix(".sha256")

    if target.is_file() and marker.is_file():
        try:
            if marker.read_text(encoding="utf-8").strip() == digest:
                return target.read_text(encoding="utf-8"), True
        except OSError:
            pass  # unreadable cache is a cache miss, never a failure

    out = compile_scene(scene_id, spec, state, nonce=nonce)
    target.parent.mkdir(parents=True, exist_ok=True)
    tmp = target.with_suffix(".html.tmp")
    tmp.write_text(out, encoding="utf-8")
    os.replace(tmp, target)
    marker.write_text(digest, encoding="utf-8")
    return out, False
